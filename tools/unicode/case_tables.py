"""Writes src/exec/unicode_case.inc: the codepoints DuckDB's upper() and lower() change, and what to.

DuckDB maps each codepoint of a VARCHAR by its bundled utf8proc's simple case mapping, whose Unicode
version differs from the utf8proc Arrow links (conda and the static build each bring their own), so
antb1 carries DuckDB's table instead of calling Arrow's utf8_upper and utf8_lower (ADR 0037's FN4).
Every mapping is one codepoint to one codepoint. Run with the pinned DuckDB CLI:

    python3 tools/unicode/case_tables.py .pixi/envs/default/bin/duckdb > src/exec/unicode_case.inc

The test tests/slt/tests/case_mapping_oracle_test.cc checks the table against the DuckDB library.
"""

import json
import subprocess
import sys


def mapping(duckdb: str, function: str) -> list[tuple[int, int]]:
    sql = (
        f"SELECT r AS cp, unicode({function}(chr(r::INTEGER))) AS to_cp, "
        f"length({function}(chr(r::INTEGER))) AS n FROM range(1, 1114112) t(r) "
        f"WHERE (r < 55296 OR r > 57343) AND {function}(chr(r::INTEGER)) <> chr(r::INTEGER) ORDER BY r"
    )
    out = subprocess.run([duckdb, "-json", "-c", sql], check=True, capture_output=True, text=True)
    rows = json.loads(out.stdout or "[]")
    several = [row["cp"] for row in rows if int(row["n"]) != 1]
    if several:
        sys.exit(f"{function}() maps {len(several)} codepoints to several, first U+{int(several[0]):04X}")
    return [(int(row["cp"]), int(row["to_cp"])) for row in rows]


def write(name: str, pairs: list[tuple[int, int]]) -> None:
    print(f"// clang-format off\ninline constexpr std::array<CaseMapping, {len(pairs)}> {name}{{{{")
    for i in range(0, len(pairs), 4):
        print("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in pairs[i : i + 4]))
    print("}};\n// clang-format on")


def main() -> None:
    duckdb = sys.argv[1]
    version = subprocess.run([duckdb, "-version"], check=True, capture_output=True, text=True)
    print("// Generated by tools/unicode/case_tables.py from DuckDB " + version.stdout.split()[0] + "; do not edit.")
    print("// The codepoints DuckDB's upper() and lower() change, sorted, each to one codepoint.")
    write("kUpperCase", mapping(duckdb, "upper"))
    write("kLowerCase", mapping(duckdb, "lower"))


if __name__ == "__main__":
    main()
